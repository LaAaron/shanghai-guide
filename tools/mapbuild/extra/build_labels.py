"""Turn labels_src.pkl into the app's label format (guides/shenzhen/labels.js): ROAD_NAMES [[zh, en]],
ROAD_POLYS [[name index, class, delta-encoded GCJ-02 lat/lng *1e5, junction distances in metres]], AREAS [[kind, en, zh, lat, lng, width m, height m]].
Road classes: 0 motorway, 1 trunk, 2 primary, 3 secondary/tertiary, 4 river, 5 smaller named streets."""
import pickle, json, sys, os, collections, math, re
import numpy as np, shapely, shapely.wkb
from shapely import STRtree
from shapely.ops import linemerge
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
from build_tiles import gcj

d = pickle.load(open('labels_src.pkl', 'rb'))
en_extra = json.load(open('en_names.json', encoding='utf-8')) if os.path.exists('en_names.json') else {}
CLS = {'motorway': 0, 'trunk': 1, 'primary': 2, 'secondary': 3, 'tertiary': 3, 'residential': 5, 'unclassified': 5, 'living_street': 5}
def conv(g): return shapely.transform(g, lambda a: np.column_stack(gcj(a[:, 0], a[:, 1])))
LAT0 = 22.54; KX, KY = 111320 * math.cos(math.radians(LAT0)), 110860
def to_m(g): return shapely.transform(g, lambda a: np.column_stack([a[:, 0] * KX, a[:, 1] * KY]))
def from_m(g): return shapely.transform(g, lambda a: np.column_stack([a[:, 0] / KX, a[:, 1] / KY]))
def clean_zh(s): return re.split(r'\s+(?=[A-Za-z])', s.strip())[0]       # "后海灣 Deep Bay - 深圳湾 Shenzhen Bay" style: keep the first Chinese part

names, name_idx, en_votes = [], {}, collections.defaultdict(collections.Counter)
def name_id(zh):
    if zh not in name_idx: name_idx[zh] = len(names); names.append(zh)
    return name_idx[zh]

# all roads (metres, GCJ) for junctions
allroads = [to_m(conv(shapely.wkb.loads(bytes(r[0])))) for r in d['roads']]
tree = STRtree(allroads)
groups = collections.defaultdict(list)
for r, g in zip(d['roads'], allroads):
    if not r[2]: continue
    zh = clean_zh(r[2]); groups[zh].append((CLS[r[1]], g))
    if r[3]: en_votes[zh][r[3]] += 1
for r in d['water']:
    if r[3] and r[4]: en_votes[clean_zh(r[3])][r[4]] += 1
for r in d['land_use']:
    if r[3] and r[4]: en_votes[clean_zh(r[3])][r[4]] += 1

polys = []
for zh, segs in groups.items():
    cls = min(c for c, _ in segs)
    merged = linemerge([g for _, g in segs])
    for ln in (merged.geoms if hasattr(merged, 'geoms') else [merged]):
        if ln.length < 120: continue
        ln = ln.simplify(2.5)
        junc = set()
        for j in tree.query(ln.buffer(1)):
            o = allroads[j]
            if o.equals(ln): continue
            x = ln.intersection(o)
            for p in (x.geoms if hasattr(x, 'geoms') else [x]):
                if p.is_empty: continue
                pt = p if p.geom_type == 'Point' else p.centroid
                junc.add(int(round(ln.project(pt))))
        polys.append((zh, cls, ln, sorted(junc)))

# rivers: named water lines
for r in d['water']:
    g = conv(shapely.wkb.loads(bytes(r[0])))
    if g.geom_type in ('LineString', 'MultiLineString') and r[3]:
        ln = to_m(g); ln = linemerge(ln) if ln.geom_type == 'MultiLineString' else ln
        for l in (ln.geoms if hasattr(ln, 'geoms') else [ln]):
            if l.length >= 300: polys.append((clean_zh(r[3]), 4, l.simplify(4), []))

def enc(ln):
    ll = from_m(ln); c = [(round(y * 1e5), round(x * 1e5)) for x, y in ll.coords]
    out = list(c[0])
    for (a, b), (pa, pb) in zip(c[1:], c[:-1]): out += [a - pa, b - pb]
    return out
ROAD_POLYS = [[name_id(zh), cls, enc(ln), junc] for zh, cls, ln, junc in polys]

# areas: named parks, plazas, lakes / reservoirs / bays (polygons only; the app hides ones too small to label)
AREAS = []
for r in d['land_use'] + d['water']:
    g = conv(shapely.wkb.loads(bytes(r[0])))
    if g.geom_type not in ('Polygon', 'MultiPolygon') or not r[3]: continue
    sub = r[1]
    kind = 'p' if sub in ('park', 'recreation', 'protected') or r[2] in ('park', 'garden') else 's' if sub == 'pedestrian' else 'w' if r in d['water'] else None
    if not kind: continue
    gm = to_m(g); x0, y0, x1, y1 = gm.bounds
    if (x1 - x0) * (y1 - y0) < 150 * 150: continue
    c = g.representative_point(); zh = clean_zh(r[3])
    AREAS.append([kind, zh, zh, round(c.y, 5), round(c.x, 5), round(x1 - x0), round(y1 - y0)])

used = set(names) | {a[1] for a in AREAS}
def en_of(zh): return (en_votes[zh].most_common(1)[0][0] if en_votes.get(zh) else en_extra.get(zh, ''))
missing = sorted(z for z in used if not en_of(z))
json.dump(missing, open('missing_en.json', 'w'), ensure_ascii=False)
ROAD_NAMES = [[zh, en_of(zh)] for zh in names]
for a in AREAS: a[1] = en_of(a[2]); a[2] = a[2] if a[1] != a[2] else ''
js = ('/* Shenzhen road and area names: OpenStreetMap/Overture Maps data (ODbL), converted to GCJ-02. Generated by tools/mapbuild/extra/build_labels.py. */\n'
      'window.SG = window.SG || {};\nSG.ROAD_NAMES = ' + json.dumps(ROAD_NAMES, ensure_ascii=False, separators=(',', ':')) +
      ';\nSG.ROAD_POLYS = ' + json.dumps(ROAD_POLYS, separators=(',', ':')) + ';\nSG.AREAS = ' + json.dumps(AREAS, ensure_ascii=False, separators=(',', ':')) + ';\n')
open('labels.js', 'w', encoding='utf-8').write(js)
print('names %d, lines %d (by class %s), areas %d (%s), missing English %d, %.2f MB' % (len(names), len(ROAD_POLYS),
      dict(collections.Counter(p[1] for p in ROAD_POLYS)), len(AREAS), dict(collections.Counter(a[0] for a in AREAS)), len(missing), len(js.encode()) / 1e6))
